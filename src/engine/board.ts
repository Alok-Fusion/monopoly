export function getTile(index: number): TileDefinition {
  const norm = ((index % BOARD_SIZE) + BOARD_SIZE) % BOARD_SIZE;
  return TILES[norm]!;
}

export function isColorGroup(group: TileGroup): boolean {
  return COLOR_GROUPS.includes(group);
}
